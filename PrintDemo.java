/*Write a program that shows the difference between:

println()

print()*/

 
public class PrintDemo {
    public static void main(String[] args) {
        int i = 5;
        int y = 7;
        System.out.println("print the value i in the same line:");
        System.out.print(i + " ");
        System.out.print(y);
        System.out.println(" ");
        System.out.println("print the value i in the next line ");
        System.out.println(i);
        System.out.println(y);
    }
    
}
